#[repr(C)]
struct Entry {
    mask: Bitboard,
    magic: u64,
    shift: u32,
    offset: u32,
}

impl Entry {
    fn index(&self, blockers: Bitboard) -> usize {
        let blockers = blockers & self.mask;
        let hash = ((blockers.0 >> 63 | blockers.0) as u64).wrapping_mul(self.magic);
        ((hash >> self.shift) + self.offset as u64) as usize
    }
}

